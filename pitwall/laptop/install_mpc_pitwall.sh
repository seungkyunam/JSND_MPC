. /etc/os-release; echo "  $PRETTY_NAME / $(uname -m) / host $(hostname)"
[[ -n ${DISPLAY:-}${WAYLAND_DISPLAY:-} ]] && ok "display ${DISPLAY:-$WAYLAND_DISPLAY}" || warn "no DISPLAY here (fine over SSH; run mpc_pitwall from the desktop)"
